/**
 * Ограничение частоты запросов.
 *
 * ЗАЧЕМ. В проекте есть касса, вывод средств, промокоды и приём платежей.
 * Без ограничений один цикл в консоли браузера перебирает промокоды тысячами
 * попыток в минуту, а пачка одновременных заявок на вывод превращает проверки
 * баланса в гонку. Сервер при этом остаётся формально исправным - он честно
 * обрабатывает всё, что ему шлют.
 *
 * ПОЧЕМУ БЕЗ БИБЛИОТЕКИ. Нужен один файл на сто строк, а зависимость тянет
 * своё хранилище, свои настройки прокси и своё представление о том, кого
 * считать клиентом. Здесь считать надо по игроку, а не по адресу: за одним
 * мобильным IP сидит пол-оператора, и общий счётчик наказал бы посторонних.
 *
 * ПО ЧЕМУ СЧИТАЕМ. Если запрос прошёл авторизацию - по номеру игрока: это
 * единственный признак, который нельзя подделать, initData подписан ботом.
 * До авторизации остаётся адрес. Поэтому ограничитель ставится ПОСЛЕ auth
 * везде, где это возможно.
 *
 * ОКНО СКОЛЬЗЯЩЕЕ, А НЕ ФИКСИРОВАННОЕ. С фиксированным окном лимит «10 в
 * минуту» пропускает 20 запросов подряд на стыке двух минут - ровно в тот
 * момент, когда это опаснее всего. Здесь хранятся отметки времени попыток, и
 * лимит держится на любом отрезке.
 *
 * ПАМЯТЬ. Ключи чистятся по таймеру, иначе множество за сутки вырастет на
 * каждого, кто хоть раз зашёл. Таймер unref, чтобы не держать процесс живым.
 */

/** Как часто выметаем протухшие ключи. */
const SWEEP_MS = 60_000;

/**
 * Один ограничитель: сколько запросов за какое окно.
 *
 * @param {object} opts
 * @param {number} opts.limit   сколько запросов разрешено
 * @param {number} opts.windowMs за какое окно, миллисекунд
 * @param {string} opts.name    имя корзины: у каждой свой счётчик
 */
export function rateLimit({ limit, windowMs, name }) {
  const hits = new Map();

  const sweep = setInterval(() => {
    const edge = Date.now() - windowMs;
    for (const [key, times] of hits) {
      const kept = times.filter((t) => t > edge);
      if (kept.length) hits.set(key, kept);
      else hits.delete(key);
    }
  }, SWEEP_MS);
  sweep.unref?.();

  return function limiter(req, res, next) {
    // Игрок известен - считаем по нему. Нет - по адресу; за адресом стоит
    // trust proxy, иначе все запросы из-за nginx выглядели бы как один клиент.
    const who = req.player?.id ? `u${req.player.id}` : `ip${req.ip}`;
    const key = `${name}:${who}`;

    const now = Date.now();
    const edge = now - windowMs;
    const times = (hits.get(key) || []).filter((t) => t > edge);

    if (times.length >= limit) {
      // Клиенту говорим, когда можно повторить: без этого он будет долбиться
      // в стену и держать нагрузку, которую мы только что отклонили.
      const retryAfter = Math.ceil((times[0] + windowMs - now) / 1000);
      res.set('Retry-After', String(retryAfter));
      hits.set(key, times);
      return res.status(429).json({
        error: 'RATE_LIMITED',
        message: `Слишком часто. Повторите через ${retryAfter} с`,
        retryAfter,
      });
    }

    times.push(now);
    hits.set(key, times);
    next();
  };
}

/**
 * Порог корзины: из настроек, иначе значение по умолчанию.
 *
 * Настройками пользуются два раза. Первый - если поток живых игроков упрётся
 * в потолок и его надо поднять, не трогая код. Второй - тесты: они шлют
 * запросы вплотную, без пауз на анимацию, и на человеческих порогах упёрлись
 * бы в собственный ограничитель. Поднимать порог в тестах честнее, чем
 * выключать ограничитель совсем: выключенный он ни разу не проверен.
 */
function threshold(name, fallback) {
  const raw = Number(process.env[`RATE_LIMIT_${name.toUpperCase()}`]);
  return Number.isFinite(raw) && raw > 0 ? raw : fallback;
}

/**
 * Готовые корзины.
 *
 * Пороги выбраны так, чтобы живой игрок их не заметил, а перебор упёрся:
 * человек не открывает кейс чаще раза в несколько секунд (один прокрут идёт
 * восемь, самое частое - автосерия, около двадцати пяти в минуту), не заводит
 * вывод дважды в минуту и не вводит десяток промокодов подряд.
 */
const bucket = (name, limit) =>
  rateLimit({ name, limit: threshold(name, limit), windowMs: 60_000 });

export const limits = {
  /** Деньги: открытие кейсов, ставки, покупка фриспинов. */
  play: bucket('play', 90),

  /** Касса: заявки на вывод и пополнение. */
  cashier: bucket('cashier', 12),

  /** Подбор: промокоды и всё, что проверяется по секрету. */
  guess: bucket('guess', 8),

  /** Чтение: списки, история, лента. Щедро, но не бесконечно. */
  read: bucket('read', 240),

  /** Приём SMS от платёжного шлюза: считается по устройству, а не по игроку. */
  webhook: bucket('webhook', 120),
};

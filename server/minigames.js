function buildOption(gameId, index, raw) {
  const [label, hint, outcomes, view = {}] = raw;

  const total = outcomes.reduce((s, o) => s + o.w * o.m, 0);
  if (!(total > 0)) throw new Error(`[${gameId}/${label}] пустая таблица выплат`);

  // Масштаб весов решается: q такое, что Σ p·m = rtp ровно.
  const q = MINI_RTP / total;
  const weight = outcomes.reduce((s, o) => s + o.w, 0);
  const lose = 1 - q * weight;

  if (!(lose >= 0) || !(lose < 1)) {
    throw new Error(
      `[${gameId}/${label}] шанс проигрыша ${lose.toFixed(4)}. ` +
      `Выплаты слишком щедры: Σw=${weight.toFixed(3)} при среднем множителе ` +
      `${(total / weight).toFixed(2)}x.`
    );
  }

  const wins = outcomes.map((o, i) => ({
    id: `${gameId}_${index}_${i}`,
    multiplier: o.m,
    probability: q * o.w,
  }));

  for (const w of wins) {
    if (!(w.probability > 0) || !(w.probability < 1)) {
      throw new Error(`[${gameId}/${label}] исход ×${w.multiplier} получил шанс ${w.probability}`);
    }
  }

  if (view.hits && view.hits.length !== wins.length) {
    throw new Error(
      `[${gameId}/${label}] подписей совпадений ${view.hits.length}, а исходов ${wins.length}. ` +
      `Клиент нарисует не то число совпадений, которое оплачено.`
    );
  }
  if (view.combos && view.combos.length !== wins.length) {
    throw new Error(
      `[${gameId}/${label}] подписей комбинаций ${view.combos.length}, а исходов ${wins.length}. ` +
      `Клиент назовёт комбинацию, за которую заплачено не столько.`
    );
  }

  return {
    label, hint, view, lose, wins,
    top: Math.max(...wins.map((w) => w.multiplier)),
    winChance: 1 - lose,
  };
}

function buildGame(spec) {
  const [id, name, tagline, family, hue, bet, options] = spec;
  if (!FAMILY_BY_ID.has(family)) throw new Error(`[${id}] неизвестное семейство ${family}`);

  const built = options.map((raw, i) => buildOption(id, i, raw));
  return {
    id, name, tagline, family, hue,
    minBet: bet[0],
    maxBet: bet[1],
    rtp: MINI_RTP,
    art: artFor(id, family),
    options: built,
    top: Math.max(...built.map((o) => o.top)),
  };
}

export const MINIGAMES = SPECS.map(buildGame);
export const MINIGAME_BY_ID = new Map(MINIGAMES.map((g) => [g.id, g]));

export function getMinigame(id) {
  return MINIGAME_BY_ID.get(String(id)) || null;
}


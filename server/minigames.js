/**
 * Роняет приложение, если хоть одна таблица не сходится.
 *
 * Мини-игр пятьдесят, и таблиц у них больше сотни. Заметить глазами, что в
 * одной из них отдача уехала на процент, невозможно - поэтому проверка
 * обязательная и на старте, как у кейсов.
 */
export function validateMinigames() {
  const report = [];
  const seen = new Set();

  for (const game of MINIGAMES) {
    if (seen.has(game.id)) throw new Error(`Повтор идентификатора мини-игры: ${game.id}`);
    seen.add(game.id);

    if (!(game.minBet > 0) || !(game.maxBet > game.minBet)) {
      throw new Error(`[${game.id}] границы ставки заданы неверно`);
    }

    for (const option of game.options) {
      const sum = option.lose + option.wins.reduce((s, w) => s + w.probability, 0);
      if (Math.abs(sum - 1) > 1e-9) {
        throw new Error(`[${game.id}/${option.label}] сумма вероятностей ${sum}`);
      }
      const ev = option.wins.reduce((s, w) => s + w.probability * w.multiplier, 0);
      if (Math.abs(ev - MINI_RTP) > 1e-9) {
        throw new Error(`[${game.id}/${option.label}] отдача ${ev}, ожидалась ${MINI_RTP}`);
      }
    }

    if (!GAME_ART[game.id]) {
      // Не ошибка сборки, но повод заметить: полка из пятидесяти карточек с
      // восемью картинками читается как сбой вёрстки, а не как выбор.
      throw new Error(`[${game.id}] нет своего значка в GAME_ART`);
    }

    report.push({
      id: game.id,
      название: game.name,
      семейство: game.family,
      вариантов: game.options.length,
      'потолок x': game.top,
      'шанс выигрыша': game.options
        .map((o) => `${(o.winChance * 100).toFixed(0)}%`).join(' / '),
    });
  }

  return report;
}


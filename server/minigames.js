/** Один выигрышный исход. Вероятность посчитается сама: p = rtp / m. */
const one = (m) => [{ m, w: 1 }];

/** Лесенка множителей с весами. Вес это форма, а не шанс. */
const ladder = (...pairs) => pairs.map(([m, w]) => ({ m, w }));

/**
 * Дорожка из n шагов: каждый шаг умножает на step, дошёл до конца - забрал.
 *
 * Исход ровно один (дошёл), поэтому вероятность дойти решается уравнением.
 * Игрок выбирает n до старта, и выбор настоящий: длинная дорожка платит
 * больше и срывается чаще, а отдача у всех длин одна.
 */
const walk = (n, step) => one(Number(Math.pow(step, n).toFixed(2)));

/**
 * Поле: открыть k безопасных клеток из size при traps ловушках.
 *
 * Множитель выведен из честной цены такого события без учёта отдачи, а
 * отдачу потом наводит решатель. Так выплата растёт с риском сама, и её не
 * приходится подбирать руками для каждой из пяти игр этого семейства.
 */
const sweep = (size, traps, k) => {
  let safe = 1;
  for (let i = 0; i < k; i++) safe *= (size - traps - i) / (size - i);
  // Два знака, а не четыре: «×1.49» читается, «×1.4935» выглядит сбоем.
  // Отдачу это не трогает, её всё равно наводит решатель.
  return one(Number((1 / safe).toFixed(2)));
};


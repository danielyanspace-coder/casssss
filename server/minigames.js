/**
 * Мини-игры: пятьдесят коротких розыгрышей.
 *
 * ОДИН РЕШАТЕЛЬ НА ВСЕХ. У игры есть варианты (между ними игрок выбирает до
 * розыгрыша), у варианта - список выигрышных исходов: множитель и вес.
 * Вероятности не задаются руками: масштаб весов решается уравнением так,
 * чтобы матожидание в точности равнялось отдаче.
 *
 *     q = rtp / Σ(w·m),   p_i = q·w_i,   p_проигрыша = 1 - q·Σw
 *
 * Отсюда два следствия, ради которых это и сделано:
 *
 *   1. Добавить игре «приятный исход» и случайно увести её в минус для кассы
 *      невозможно: вес перераспределяет вероятность, а не создаёт её.
 *   2. Варианты одной игры с разными выплатами автоматически имеют одинаковую
 *      отдачу. «Осторожный» и «рисковый» различаются разбросом, а не тем,
 *      что один выгоднее.
 *
 * СЕМЕЙСТВО - ЭТО МЕХАНИКА, А НЕ ОФОРМЛЕНИЕ. Шестнадцать семейств, и у
 * каждого своё движение на экране: множитель, который бежит вверх и может
 * взорваться; шар, который надувается рывками; фигурка, идущая по этажам;
 * барабан, который тормозит; тираж лото, выпадающий по одному числу; заезд,
 * где бегуны едут наперегонки. Игра отличается от соседней тем, ЧТО
 * происходит, а не тем, какого цвета у неё карточка.
 *
 * ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО: игр на реакцию. Исход решает сервер, и если бы
 * игрок «ловил» бегунок или успевал нажать, его ловкость всё равно ничего не
 * меняла бы. Нарисовать полосу, которую якобы можно поймать, а на деле не
 * влиять ни на что - обман, и он вскрывается. Решение принимается ДО
 * розыгрыша, и оно настоящее: докуда лететь, сколько качать, как далеко
 * идти, на что ставить.
 */


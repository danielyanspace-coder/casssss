/**
 * Разыгрывает один раунд по готовому случайному числу из provably fair.
 *
 * Возвращает и множитель, и ИНДЕКС исхода: клиенту он нужен, чтобы показать
 * именно тот сектор, ту клетку и ту грань, которые соответствуют результату.
 * Без индекса анимация выбирала бы картинку сама, и однажды колесо встало бы
 * не на то, что написано в окне выигрыша.
 */
export function resolveMinigame(game, optionIndex, roll) {
  const option = game.options[optionIndex];
  if (!option) throw Object.assign(new Error('Такого варианта нет'), { code: 'BAD' });

  let acc = 0;
  for (let i = 0; i < option.wins.length; i++) {
    acc += option.wins[i].probability;
    if (roll < acc) {
      return { multiplier: option.wins[i].multiplier, outcomeIndex: i, win: true };
    }
  }
  return { multiplier: 0, outcomeIndex: -1, win: false };
}


/**
 * Значок монеты как строка SVG.
 *
 * Возвращается именно строка: клиент собирает разметку шаблонами, и вставлять
 * узел через DOM ради одного значка было бы лишней работой.
 */
export function coinMark(code, size = 34) {
  const key = String(code || '').toUpperCase();
  const color = coinColor(key);
  const glyph = GLYPHS[key];

  // Незнакомая монета: круг и её код в две-три буквы.
  const body = glyph || `<text x="16" y="21" text-anchor="middle"
      font-family="system-ui, -apple-system, Segoe UI, sans-serif"
      font-size="${key.length > 3 ? 9 : 11}" font-weight="700" fill="#fff">${key.slice(0, 4)}</text>`;

  return `<svg class="coin-mark" width="${size}" height="${size}" viewBox="0 0 32 32"
      role="img" aria-label="${key}">
    <circle cx="16" cy="16" r="16" fill="${color}"/>
    ${body}
  </svg>`;
}

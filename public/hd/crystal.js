/**
 * Кристалл. Порядок = порядок предметов в server/themes.js.
 *
 * Двадцать камней в одной теме - главный риск повтора: цвет один у трёх-четырёх
 * предметов, поэтому они различаются ОГРАНКОЙ и ОПРАВОЙ. Ступенчатая, бриллиант
 * сбоку, бриллиант сверху, кабошон, срез, сырой кристалл, жеода.
 */
import { hdRect, hdEll, hdNgon, hdPoly, hdStar, hdMix } from './kit.js';

export const HD_CRYSTAL = (() => {
  /** Цвет грани по яркости 0..1 из четырёх тонов материала. */
  const shade = (k, m, b) => {
    const t = k.tone(m), ramp = [t[3], t[2], t[1], t[0]];
    b = Math.min(1, Math.max(0, b)) * 3;
    const i = Math.min(2, Math.floor(b));
    return hdMix(ramp[i], ramp[i + 1], b - i);
  };

  /** Бриллиант сбоку: площадка, корона, рундист, павильон. */
  const brilliantSide = (k, cx, cy, w, m) => {
    const h1 = w * 0.22, h2 = w * 0.5, tw = w * 0.56;
    const L = cx - w / 2, R = cx + w / 2, T = cy - h1;
    let s = '';
    const crown = [[L, cy], [cx - tw / 2, T], [cx - tw / 6, T], [cx - w / 6, cy]];
    s += k.f(hdPoly(crown), shade(k, m, 0.85));
    s += k.f(hdPoly([[cx - w / 6, cy], [cx - tw / 6, T], [cx + tw / 6, T], [cx + w / 6, cy]]), shade(k, m, 0.95));
    s += k.f(hdPoly([[cx + w / 6, cy], [cx + tw / 6, T], [cx + tw / 2, T], [R, cy]]), shade(k, m, 0.55));
    const tip = [cx, cy + h2];
    s += k.f(hdPoly([[L, cy], [cx - w / 6, cy], tip]), shade(k, m, 0.5));
    s += k.f(hdPoly([[cx - w / 6, cy], [cx, cy], tip]), shade(k, m, 0.75));
    s += k.f(hdPoly([[cx, cy], [cx + w / 6, cy], tip]), shade(k, m, 0.3));
    s += k.f(hdPoly([[cx + w / 6, cy], [R, cy], tip]), shade(k, m, 0.15));
    const t = k.tone(m);
    s += k.s(`M${L} ${cy}H${R}M${cx - w / 6} ${cy}L${cx - tw / 6} ${T}M${cx + w / 6} ${cy}L${cx + tw / 6} ${T}` +
      `M${cx - w / 6} ${cy}L${tip[0]} ${tip[1]}M${cx + w / 6} ${cy}L${tip[0]} ${tip[1]}M${cx} ${cy}L${tip[0]} ${tip[1]}`, t[0], 0.6, 0.5);
    s += k.p(hdPoly([[L, cy], [cx - tw / 2, T], [cx + tw / 2, T], [R, cy], tip]), m, 'd', { w: 1.6, g: 0 }).replace(/fill="[^"]*"/, 'fill="none"');
    return s;
  };

  /** Ступенчатая огранка: вложенные восьмиугольники со срезанными углами. */
  const stepCut = (k, cx, cy, w, h, m, steps = 4) => {
    let s = '';
    for (let i = 0; i < steps; i++) {
      const f = 1 - i * 0.2, c = Math.min(w, h) * 0.18 * f;
      const x0 = cx - (w * f) / 2, y0 = cy - (h * f) / 2, x1 = cx + (w * f) / 2, y1 = cy + (h * f) / 2;
      const d = hdPoly([[x0 + c, y0], [x1 - c, y0], [x1, y0 + c], [x1, y1 - c], [x1 - c, y1], [x0 + c, y1], [x0, y1 - c], [x0, y0 + c]]);
      s += i === 0 ? k.p(d, m, 'd', { w: 1.6 }) : k.p(d, m, i % 2 ? 'm' : 'd', { w: 0.6, g: i === steps - 1 ? 0.8 : 0.2 });
    }
    return s;
  };

  /** Четыре лапки крапана поверх камня. */
  const prongs = (k, pts, m = 'gold') => pts.map(([x, y]) => k.p(`M${x} ${y - 3}q3 0 3 3t-3 3q-2 0-2-3t2-3Z`, m, 'd', { w: 0.8 })).join('');

  /** Призма кристалла: шестигранная, с заострённой верхушкой. */
  const prism = (k, x, y, w, h, rot, m) => k.g(`rotate(${rot} ${x} ${y})`,
    k.p(`M${x - w / 2} ${y}V${y - h}L${x} ${y - h - w * 0.7}L${x + w / 2} ${y - h}V${y}Z`, m, 'c', { w: 1.2 }) +
    k.p(`M${x - w / 2} ${y - h}L${x} ${y - h - w * 0.7}L${x} ${y - h + w * 0.2}Z`, m, 'd', { w: 0, g: 0.9 }) +
    k.s(`M${x} ${y - h + w * 0.2}V${y}`, k.tone(m)[0], 0.6, 0.6));

  return [
    /* 0 Мутный осколок - сырой мутный кварц, матовый, без огранки. */
    (k) => k.aura('#b8c4d6', 0.34) + k.shadow(50, 86, 26) +
      k.p('M24 70L32 34L52 20L72 38L76 68L54 80Z', ['#f2f4f8', '#c4ccd8', '#8a94a6', '#3a404c', 0.35], 'd', { w: 1.6 }) +
      k.p('M32 34L52 20L50 46Z', '#e8ecf4', 'd', { w: 0, g: 0.2, op: 0.8 }) +
      k.p('M50 46L72 38L76 68Z', '#8a94a6', 'd', { w: 0, g: 0, op: 0.6 }) +
      k.s('M50 46L54 80M50 46L24 70', '#ffffff', 0.8, 0.4),

    /* 1 Кварцевая крошка - щётка мелких прозрачных призм. */
    (k) => k.aura('#d8e8ff', 0.38) + k.shadow(50, 88, 30) +
      k.p('M18 84Q30 70 50 72Q70 70 82 84Z', 'granite', 'd', { w: 1.3 }) +
      [[30, 80, 7, 16, -24], [40, 78, 8, 24, -10], [52, 78, 9, 30, 4], [62, 80, 7, 20, 18], [70, 82, 6, 12, 30], [46, 82, 6, 12, -30]].map(([x, y, w, h, r]) =>
        prism(k, x, y, w, h, r, 'diamond')).join(''),

    /* 2 Аметист - половинка жеоды: серая корка, фиолетовые кристаллы внутри. */
    (k) => {
      let teeth = '';
      for (let i = 0; i < 14; i++) {
        const a = (i / 14) * Math.PI * 2, r1 = 22, r2 = 10 + (i % 3) * 3;
        const x1 = 50 + r1 * Math.cos(a), y1 = 52 + r1 * 0.8 * Math.sin(a);
        const a2 = a + Math.PI / 14;
        teeth += k.f(hdPoly([[x1, y1], [50 + r2 * Math.cos(a2), 52 + r2 * 0.8 * Math.sin(a2)],
          [50 + r1 * Math.cos(a + Math.PI / 7), 52 + r1 * 0.8 * Math.sin(a + Math.PI / 7)]]), shade(k, 'amethyst', 0.3 + 0.6 * ((Math.cos(a - 3.9) + 1) / 2)));
      }
      return k.aura('#b04dff', 0.46) + k.shadow(50, 88, 32) +
        k.e(50, 52, 32, 28, 'stone', 'd', { w: 1.6, b: true }) +
        k.e(50, 52, 26, 22, 'amethyst', 'r', { w: 1.2 }) + teeth +
        // Середина не тёмная: тёмный центр в светлом кольце читается как глаз.
        [[46, 50, 5, -20], [54, 54, 6, 15], [50, 46, 4, 0], [42, 56, 3.6, -40], [58, 46, 3.4, 30]].map(([x, y, s2, r]) =>
          k.g(`rotate(${r} ${x} ${y})`, k.p(`M${x - s2 * 0.5} ${y + s2}L${x - s2 * 0.5} ${y - s2 * 0.4}L${x} ${y - s2 * 1.2}L${x + s2 * 0.5} ${y - s2 * 0.4}L${x + s2 * 0.5} ${y + s2}Z`, 'amethyst', 'c', { w: 0.8 }))).join('') +
        k.spark(40, 42, 4);
    },

    /* 3 Дымчатый топаз - коричневая ступенчатая огранка, вытянутый прямоугольник. */
    (k) => k.aura('#c48a4a', 0.4) + k.shadow(50, 86, 26) +
      stepCut(k, 50, 50, 44, 60, ['#ffe2c0', '#a8642a', '#5c3010', '#1e0c02', 1]) +
      k.spark(36, 30, 4),

    /* 4 Сапфир - овальный бриллиант синего цвета, вид сверху. */
    (k) => k.aura('#2f6dff', 0.5) + k.shadow(50, 88, 26) +
      k.gem(50, 50, 30, 'sapphire', { n: 10, sy: 0.72, t: 0.55 }) +
      k.spark(36, 38, 5),

    /* 5 Турмалин - арбузный срез: розовая середина, зелёная кайма. */
    (k) => k.aura('#ff6b9a', 0.44) + k.shadow(50, 88, 26) +
      k.p(hdPoly(hdNgon(50, 52, 32, 3, -90)).replace(/L/g, ' L'), '#2fbf5a', 'd', { w: 1.6 }) +
      k.p(hdPoly(hdNgon(50, 54, 25, 3, -90)), '#f2f8e8', 'd', { w: 0.6, g: 0.3 }) +
      k.p(hdPoly(hdNgon(50, 55, 21, 3, -90)), '#ff4d8a', 'r', { w: 0.8, g: 0.6 }) +
      k.s('M50 34L50 66M38 62L62 62', '#ffb0cc', 0.8, 0.5) + k.spark(42, 50, 3),

    /* 6 Изумруд - ступенчатая огранка в золотых крапанах. */
    (k) => k.aura('#13d67a', 0.5) + k.shadow(50, 88, 28) +
      stepCut(k, 50, 50, 60, 44, 'emerald') +
      prongs(k, [[22, 30], [78, 30], [22, 70], [78, 70]]) +
      k.spark(32, 34, 5),

    /* 7 Александрит - камень меняет цвет: половина зелёная, половина красная. */
    (k) => k.aura('#7a3dff', 0.46) + k.shadow(50, 88, 28) +
      k.gem(50, 50, 30, ['#d8ffe8', '#1fae6a', '#0a5a36', '#02200f', 1], { n: 8, rot: -67.5, t: 0.5 }) +
      k.clip('M50 0H100V100H50Z', k.gem(50, 50, 30, ['#ffd0e0', '#c81e5a', '#6a0a2e', '#22000e', 1], { n: 8, rot: -67.5, t: 0.5 })) +
      k.s('M50 20V80', '#ffffff', 0.8, 0.5) + k.spark(38, 38, 4),

    /* 8 Рубин короны - крупный кабошон в золотом обрамлении с зубцами. */
    (k) => k.aura('#ff2e55', 0.5) + k.shadow(50, 90, 30) +
      k.p('M14 70L18 36L32 50L50 26L68 50L82 36L86 70Z', 'gold', 'd', { w: 1.6, b: true }) +
      k.r(12, 66, 76, 14, 4, 'gold', 'h', { w: 1.5 }) +
      k.e(50, 56, 16, 18, 'gold', 'd', { w: 1.4 }) +
      k.o(50, 56, 13, 'ruby') +
      [18, 50, 82].map((x, i) => k.o(x, [36, 26, 36][i], 3, 'pearl')).join(''),

    /* 9 Алмаз чистой воды - классический бриллиант сбоку. */
    (k) => k.aura('#bfefff', 0.5) + k.shadow(50, 90, 26) +
      brilliantSide(k, 50, 40, 64, 'diamond') +
      k.spark(36, 30, 6) + k.spark(66, 54, 3),

    /* 10 Розовый бриллиант - огранка «сердце». */
    (k) => k.aura('#ff7ab8', 0.52) + k.shadow(50, 90, 26) +
      k.p('M50 86C38 72 16 60 16 38C16 24 26 16 36 16C44 16 48 22 50 26C52 22 56 16 64 16C74 16 84 24 84 38C84 60 62 72 50 86Z',
        ['#ffe0f0', '#ff6bb5', '#c8287a', '#4a0428', 1], 'd', { w: 1.6 }) +
      k.p('M50 30L36 26L28 40L50 72L72 40L64 26Z', '#ffb0d8', 'd', { w: 0.6, g: 0.9 }) +
      k.s('M50 30V72M28 40H72M36 26L50 40L64 26M16 38L28 40M84 38L72 40', '#fff0f8', 0.6, 0.6) +
      k.spark(32, 30, 5),

    /* 11 Кристалл творения - светящаяся радужная друза. */
    (k) => k.rays('#c9a8ff', 12, 0.3) + k.aura('#b45cff', 0.5) + k.shadow(50, 90, 30) +
      [[50, 84, 12, 40, 0, '#b45cff'], [36, 86, 9, 26, -22, '#2ec8ff'], [64, 86, 10, 28, 20, '#ff6bb5'], [26, 88, 6, 14, -40, '#3dff7a'], [74, 88, 7, 16, 38, '#ffd34d']].map(([x, y, w, h, r, c]) =>
        prism(k, x, y, w, h, r, [hdMix(c, '#ffffff', 0.8), c, hdMix(c, '#200040', 0.4), hdMix(c, '#000000', 0.7), 1])).join('') +
      k.aura('#ffffff', 0.5, 14, 50, 50) + k.spark(50, 30, 5),

    /* 12 Огранка в 100 карат - огромная капля с биркой. */
    (k) => k.aura('#9fe8ff', 0.52) + k.shadow(50, 92, 26) +
      k.p('M50 10Q74 40 74 62A24 24 0 0 1 26 62Q26 40 50 10Z', 'diamond', 'd', { w: 1.6 }) +
      k.p('M50 10L40 44L50 82L60 44Z', '#ffffff', 'd', { w: 0, g: 0.6, op: 0.6 }) +
      k.s('M50 10L40 44L26 62M50 10L60 44L74 62M40 44L50 82L60 44M40 44H60M26 62L50 82L74 62', '#5ab0e8', 0.7, 0.7) +
      k.tube('M66 26Q78 22 80 30', '#c9d4e2', 1) +
      k.g('rotate(14 82 38)', k.p('M74 32h16v12H74l-3-6Z', 'paper', 'd', { w: 1 }) + k.txt(82, 41, '100', 6, 'black', { ls: 0 })) +
      k.spark(38, 40, 5),

    /* 13 Жила самоцветов - скала, прорезанная разноцветной жилой. */
    (k) => k.aura('#ff9a3a', 0.4) + k.shadow(50, 92, 40) +
      k.p('M8 88L14 30L40 14L70 18L92 40L90 88Z', 'granite', 'd', { w: 1.6, b: true }) +
      k.p('M10 64Q30 50 50 56Q70 62 92 46L92 56Q70 72 50 66Q30 60 10 74Z', '#3a2a24', 'd', { w: 0, g: 0 }) +
      [[18, 64, 'ruby'], [28, 60, 'emerald'], [38, 58, 'sapphire'], [50, 61, 'topaz'], [62, 63, 'amethyst'], [74, 58, 'ruby'], [84, 52, 'emerald']].map(([x, y, m], i) =>
        k.gem(x, y, 5 + (i % 2), m, { n: 6, w: 0.8, rot: i * 20 })).join(''),

    /* 14 Витрина ювелира - стеклянная витрина, камни на бархате. */
    (k) => k.aura('#ffcf6a', 0.44) + k.shadow(50, 92, 40) +
      k.r(10, 66, 80, 22, 3, 'darkwood', 'h', { w: 1.5 }) +
      k.p('M14 66L20 30H80L86 66Z', '#2a0a3a', 'v', { w: 1.2, g: 0.3 }) +
      [[30, 56, 'ruby'], [44, 52, 'diamond'], [58, 54, 'emerald'], [70, 58, 'sapphire'], [38, 62, 'topaz'], [62, 62, 'amethyst']].map(([x, y, m]) =>
        k.gem(x, y, 4.4, m, { n: 8, w: 0.7 })).join('') +
      k.p('M14 66L20 30H80L86 66Z', 'glass', 'd', { w: 1.4, g: 0.9, op: 0.22 }) +
      k.r(18, 26, 64, 5, 2, 'gold', 'h', { w: 1 }) + k.hl('M24 34L20 60', 1.6, 0.6),

    /* 15 Камень без имени - чёрный опал с игрой цвета. */
    (k) => k.aura('#2ec8ff', 0.44) + k.shadow(50, 88, 28) +
      k.e(50, 52, 32, 26, ['#5a6aa8', '#141a3a', '#080c1e', '#000000', 1], 'r', { w: 1.6 }) +
      k.clip(hdEll(50, 52, 32, 26),
        // Игра цвета опала - рваные пятна, а не фигуры.
        [[36, 44, 9, 4, 30, '#2ef3ff'], [56, 40, 10, 3.4, -20, '#3dff7a'], [64, 56, 8, 4, 60, '#ff2ea6'], [42, 62, 10, 3, -40, '#ffd34d'],
          [52, 52, 7, 3, 10, '#7a3dff'], [30, 56, 6, 2.4, 80, '#3dff7a'], [68, 44, 5, 2.4, -60, '#ffd34d']].map(([x, y, rx, ry, r, c]) =>
          k.g(`rotate(${r} ${x} ${y})`, k.f(hdEll(x, y, rx, ry), c, 0.7) + k.f(hdEll(x - 1, y - 0.6, rx * 0.5, ry * 0.4), '#ffffff', 0.5))).join('')) +
      k.e(40, 40, 10, 5, '#ffffff', 'v', { w: 0, g: 0, op: 0.5 }),

    /* 16 Коллекция дома - бархатный лоток с рядом разных камней. */
    (k) => k.aura('#7a5cff', 0.46) + k.shadow(50, 88, 40) +
      k.p('M8 44L92 44L86 80H14Z', '#1a2a6a', 'd', { w: 1.5, g: 0.3 }) +
      k.r(8, 40, 84, 6, 2, 'gold', 'h', { w: 1.2 }) +
      [[22, 'ruby', 10], [37, 'emerald', 4], [50, 'diamond', 8], [63, 'sapphire', 6], [78, 'topaz', 12]].map(([x, m, n]) =>
        k.e(x, 62, 6.6, 4, '#0d1640', 'd', { w: 0.6, g: 0 }) + k.gem(x, 58, 6, m, { n, w: 0.8, sy: 0.8 })).join('') +
      k.spark(50, 50, 4),

    /* 17 Алмазный фонд - колье: ряд бриллиантов и большая подвеска. */
    (k) => {
      let row = '';
      for (let i = 0; i <= 12; i++) {
        const t = Math.PI * (0.1 + 0.8 * (i / 12));
        const x = 50 - 36 * Math.cos(t), y = 18 + 34 * Math.sin(t);
        row += k.c(x, y, 3.6, 'silver', 'r', { w: 0.5 }) + k.gem(x, y, 3, 'diamond', { n: 8, w: 0.5 });
      }
      return k.rays('#bfefff', 14, 0.34) + k.aura('#9fe8ff', 0.52) + k.shadow(50, 92, 22) +
        row + k.tube('M50 52V58', 'silver', 1.4) +
        k.p('M50 58Q64 72 50 90Q36 72 50 58Z', 'diamond', 'd', { w: 1.4 }) +
        k.s('M50 58V90M42 72H58', '#5ab0e8', 0.6, 0.6) + k.spark(50, 70, 5);
    },

    /* 18 Совершенная огранка - круглый бриллиант сверху, шестнадцать граней. */
    (k) => k.rays('#e2f7ff', 18, 0.44) + k.aura('#bfefff', 0.6) + k.shadow(50, 92, 26) +
      k.gem(50, 50, 36, 'diamond', { n: 16, t: 0.5 }) +
      k.p(hdStar(50, 48, 18, 10, 8, -90), '#ffffff', 'd', { w: 0, g: 0, op: 0.35 }) +
      k.spark(34, 34, 7) + k.spark(68, 62, 4) + k.spark(60, 28, 3),

    /* 19 Первый кристалл - парящий светящийся кристалл в орбитальных кольцах. */
    (k) => k.rays('#ffffff', 20, 0.46) + k.aura('#c9a8ff', 0.62) + k.shadow(50, 92, 20) +
      k.g('rotate(-20 50 50)', `<path d="M14 50a36 10 0 0 1 72 0" fill="none" stroke="#ffd34d" stroke-width="2"/>`) +
      k.p('M50 8L68 40L50 88L32 40Z', ['#ffffff', '#e8d8ff', '#a87aff', '#2a0a6a', 1], 'd', { w: 1.6 }) +
      k.p('M50 8L68 40L50 48Z', '#ffffff', 'd', { w: 0, g: 0.8, op: 0.7 }) + k.p('M50 48L68 40L50 88Z', '#5a2ab0', 'd', { w: 0, g: 0, op: 0.6 }) +
      k.s('M32 40H68M50 8V88', '#ffffff', 0.7, 0.6) +
      k.g('rotate(-20 50 50)', `<path d="M14 50a36 10 0 0 0 72 0" fill="none" stroke="#ffd34d" stroke-width="2"/>`) +
      k.aura('#ffffff', 0.7, 10, 50, 40) + k.spark(50, 40, 7),
  ];
})();

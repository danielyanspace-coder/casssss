/**
 * Разбор присланного макета слота GOLDEN LEGACY на отдельные картинки.
 *
 * Исходник - один PNG 1536x1024 (4854D818-1A44-4209-A778-E30D33A16C0E.png в
 * корне репозитория). В отличие от первого макета это не один экран, а целый
 * набор: слева вверху игра, справа таблица выплат, снизу рядом все окна -
 * меню, настройки, покупка бонуса, автоигра, бесплатные вращения, BIG WIN,
 * линия выигрыша, выбор ставки, «недостаточно средств».
 *
 * Целиком он в проект не идёт: это макет, а не интерфейс. Отсюда берутся
 * только рисунки - символы, логотип, колонны, арка, слои фона, кнопка
 * прокрута и картинка бонуса. Панели, плашки джекпотов, таблица и все окна
 * собираются вёрсткой: в макете надписи вшиты в пиксели, а их надо
 * переводить, менять и читать экранным дикторам.
 *
 * Запуск: node tools/slot-golden-assets.mjs [путь-к-макету]
 *
 * ПОЧЕМУ КООРДИНАТЫ ЗАШИТЫ ЧИСЛАМИ. Макет один и меняться не будет: искать
 * границы символов автоматически означало бы писать распознавание ради
 * полутора десятков прямоугольников. Числа сняты с макета по координатной
 * сетке и проверены глазами по контактному листу.
 *
 * ИМЕНА ТОЛЬКО ИЗ БУКВ, ЦИФР И ДЕФИСА: автономная сборка ищет пути
 * выражением [\w-]+\.webp и имя с точкой или кириллицей просто не увидит.
 */

import sharp from 'sharp';
import { mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SRC = process.argv[2]
  || fileURLToPath(new URL('../4854D818-1A44-4209-A778-E30D33A16C0E.png', import.meta.url));
const OUT = fileURLToPath(new URL('../public/assets/ui/', import.meta.url));

if (!existsSync(SRC)) {
  console.error(`Макет не найден: ${SRC}\n` +
    '  node tools/slot-golden-assets.mjs 4854D818-1A44-4209-A778-E30D33A16C0E.png');
  process.exit(1);
}
mkdirSync(OUT, { recursive: true });

/* ============================================================
   СИМВОЛЫ
   ============================================================ */

/**
 * Тринадцать символов: [лево, верх, ширина, высота].
 *
 * Все взяты ИЗ ТАБЛИЦЫ ВЫПЛАТ, а не с барабанов, и это осознанно: в таблице
 * они стоят на ровном тёмном фоне по одному, без соседей и без подсветки
 * барабана. На барабанах они крупнее, но каждый лежит в своей ячейке с
 * бликом, и вырезка тащит за собой кусок соседней.
 *
 * Строки выплат под символами в вырезку не попадают: границы подобраны по
 * самому рисунку.
 */
const SYMBOLS = {
  lion:    [991, 58, 74, 90],
  temple:  [1107, 60, 108, 90],
  chest:   [1274, 63, 100, 86],
  helmet:  [1415, 53, 68, 97],
  wreath:  [995, 244, 60, 70],
  amphora: [1103, 243, 55, 74],
  ace:     [1196, 254, 50, 54],
  king:    [1244, 254, 50, 54],
  queen:   [1315, 254, 50, 54],
  jack:    [1362, 252, 45, 58],
  ten:     [1428, 254, 64, 54],
  scatter: [991, 396, 94, 98],
  wild:    [1144, 394, 112, 110],
};

/** Сторона квадрата символа на выходе. Барабан рисует их в одном размере. */
const SYMBOL_SIZE = 180;

/* ============================================================
   ОСТАЛЬНАЯ ГРАФИКА
   ============================================================ */

const PIECES = {
  // Логотип вместе с подзаголовком: это и есть название игры.
  'gl-logo': [96, 22, 300, 104],

  /*
   * Рамка барабанов - древний храм: две колонны и арка над ними. Вёрстка
   * ставит колонны по краям поля, арку сверху.
   */
  /*
   * Арка берётся ТОЛЬКО ПРАВОЙ ПОЛОВИНОЙ, а вёрстка ставит её дважды, вторую
   * зеркально. Левая половина в макете лежит под подзаголовком логотипа, и
   * вырезка притащила бы «FORTUNE FAVORS THE BRAVE» поперёк балки.
   */
  'gl-arch': [420, 98, 376, 46],

  /*
   * Колонны обрезаны по 478-й строке: ниже в макете панель со ставкой и
   * кнопка автоигры, а их рисует вёрстка.
   */
  'gl-col-left': [158, 132, 62, 346],
  'gl-col-right': [733, 132, 62, 346],

  /*
   * Полоса неба. Берётся выше логотипа и плашек джекпотов: всё, что ниже,
   * уже занято ими, и вырезка притащила бы чужие надписи.
   */
  'gl-bg-sky': [20, 10, 908, 30],

  /*
   * Картинка бонусного зала из окна «БЕСПЛАТНЫЕ ВРАЩЕНИЯ». Она же уходит на
   * плашку запуска бонуса: рисовать второй зал незачем.
   */
  /*
   * Взята только верхняя полоса картинки: ниже в макете вшиты «10» и
   * «БЕСПЛАТНЫХ ВРАЩЕНИЙ», а эти надписи пишет вёрстка - число там разное.
   */
  'gl-bonus': [500, 610, 374, 70],
};

/* ============================================================
   СЛОИ ФОНА: КНОПКИ И ПЛАШКИ ЗАКРАШИВАЮТСЯ
   ============================================================ */

/**
 * Левый столбец макета - готовый слой фона: храмы на скале, водопад, факел,
 * шлем с лавровой ветвью внизу. Мешают только три круглые кнопки меню.
 *
 * Вместо того чтобы резать столбец выше и ниже кнопок (получились бы два
 * куска со швом), кнопки заклеиваются куском водопада, взятым правее них.
 * Шов уходит в падающую воду и в готовом виде незаметен.
 */
async function buildLeft() {
  const patch = await sharp(SRC)
    .extract({ left: 118, top: 240, width: 48, height: 140 })
    .toBuffer();

  return sharp(SRC)
    .extract({ left: 8, top: 118, width: 158, height: 450 })
    .composite([
      { input: patch, left: 22, top: 122 },
      { input: patch, left: 58, top: 122 },
    ])
    .webp({ quality: 86 })
    .toFile(OUT + 'gl-bg-left.webp');
}

/**
 * Правый столбец: статуя с копьём, факел, чаша, монеты. Мешает плашка
 * «КУПИТЬ БОНУС» - её заклеиваем куском скалы снизу, оттуда же по цвету.
 *
 * Столбец обрезан по 490-й строке: ниже в макете стоит круглая кнопка
 * автоигры, а её рисует вёрстка.
 */
async function buildRight() {
  const patch = await sharp(SRC)
    .extract({ left: 795, top: 385, width: 96, height: 96 })
    .toBuffer();

  return sharp(SRC)
    .extract({ left: 790, top: 96, width: 155, height: 394 })
    .composite([{ input: patch, left: 43, top: 190 }])
    .webp({ quality: 86 })
    .toFile(OUT + 'gl-bg-right.webp');
}

/* ============================================================
   СБОРКА
   ============================================================ */

/** Круглая вырезка: всё вне круга становится прозрачным. */
async function circle(name, [left, top, size]) {
  const mask = Buffer.from(
    `<svg width="${size}" height="${size}"><circle cx="${size / 2}" cy="${size / 2}" ` +
    `r="${size / 2}" fill="#fff"/></svg>`);
  await sharp(SRC)
    .extract({ left, top, width: size, height: size })
    .composite([{ input: mask, blend: 'dest-in' }])
    .webp({ quality: 92 })
    .toFile(OUT + name + '.webp');
}

const made = [];

for (const [name, [left, top, width, height]] of Object.entries(SYMBOLS)) {
  /*
   * contain, а не cover: символы разной формы - амфора вытянута, венок почти
   * квадратный. Обрезка по квадрату съела бы амфоре горло, поэтому она
   * вписывается целиком, а поля остаются прозрачными.
   */
  await sharp(SRC)
    .extract({ left, top, width, height })
    .resize(SYMBOL_SIZE, SYMBOL_SIZE, {
      fit: 'contain',
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .webp({ quality: 90 })
    .toFile(`${OUT}gl-sym-${name}.webp`);
  made.push(`gl-sym-${name}`);
}

for (const [name, [left, top, width, height]] of Object.entries(PIECES)) {
  await sharp(SRC)
    .extract({ left, top, width, height })
    .webp({ quality: 88 })
    .toFile(`${OUT}${name}.webp`);
  made.push(name);
}

// Кнопка прокрута вырезается кругом: квадрат притащил бы с собой углы
// каменной ступени, а кнопка лежит поверх неё и углы были бы видны.
await circle('gl-spin', [630, 457, 110]);
made.push('gl-spin');

await buildLeft();
made.push('gl-bg-left');
await buildRight();
made.push('gl-bg-right');

/*
 * Обложка для полки слотов. Берётся сам игровой экран целиком и сжимается:
 * это самый честный значок игры, какой только может быть - ровно то, что
 * игрок увидит, нажав.
 */
await sharp(SRC)
  .extract({ left: 8, top: 8, width: 938, height: 556 })
  .resize(640, 380, { fit: 'cover' })
  .webp({ quality: 84 })
  .toFile(OUT + 'slot-cover-golden.webp');
made.push('slot-cover-golden');

console.log(`Готово: ${made.length} файлов в public/assets/ui/`);
console.log(made.join(' '));

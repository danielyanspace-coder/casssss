/**
 * Левый столбец макета - готовый слой фона: скала, водопад, море, лодка и
 * груда золота внизу. Мешают только три круглые кнопки меню поверх него.
 *
 * Вместо того чтобы обрезать столбец выше и ниже кнопок (получились бы два
 * куска со швом), кнопки заклеиваются полосой скалы, взятой правее них.
 * Шов уходит в текстуру камня и в готовом виде незаметен.
 */
async function buildCliff() {
  const patch = await sharp(SRC)
    .extract({ left: 112, top: 196, width: 74, height: 228 })
    .toBuffer();

  /*
   * Столбец берётся с 180-й строки и до 870-й: выше него в макете логотип,
   * ниже - карточка механики. И то и другое рисует вёрстка, в фоне им не
   * место.
   */
  return sharp(SRC)
    .extract({ left: 0, top: 180, width: 190, height: 690 })
    .composite([
      { input: patch, left: 18, top: 16 },
      { input: patch, left: 60, top: 16 },
    ])
    .webp({ quality: 86 })
    .toFile(OUT + 'slot-bg-cliff.webp');
}


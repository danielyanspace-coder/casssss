/** Круглая вырезка: всё вне круга становится прозрачным. */
async function circle(name, [left, top, size]) {
  const mask = Buffer.from(
    `<svg width="${size}" height="${size}"><circle cx="${size / 2}" cy="${size / 2}" ` +
    `r="${size / 2}" fill="#fff"/></svg>`);
  await sharp(SRC)
    .extract({ left, top, width: size, height: size })
    .composite([{ input: mask, blend: 'dest-in' }])
    .webp({ quality: 92 })
    .toFile(OUT + name + '.webp');
}

const made = [];

for (const [name, [left, top, width, height]] of Object.entries(SYMBOLS)) {
  /*
   * contain, а не cover: символы в макете разной формы - подзорная труба
   * вытянута, корона почти квадратная. Обрезка по квадрату съела бы трубе
   * концы, поэтому она вписывается целиком, а поля остаются прозрачными.
   */
  await sharp(SRC)
    .extract({ left, top, width, height })
    .resize(SYMBOL_SIZE, SYMBOL_SIZE, {
      fit: 'contain',
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .webp({ quality: 90 })
    .toFile(`${OUT}slot-sym-${name}.webp`);
  made.push(`slot-sym-${name}`);
}

for (const [name, [left, top, width, height]] of Object.entries(PIECES)) {
  await sharp(SRC)
    .extract({ left, top, width, height })
    .webp({ quality: 88 })
    .toFile(`${OUT}${name}.webp`);
  made.push(name);
}

// Кнопка SPIN вырезается кругом: квадрат притащил бы с собой углы фона,
// а кнопка лежит поверх доски рамки и углы были бы видны.
await circle('slot-spin', [606, 702, 172]);
made.push('slot-spin');

await buildCliff();
made.push('slot-bg-cliff');

/*
 * Обложка для полки слотов. Берётся сам игровой экран и сжимается: это самый
 * честный значок игры, какой только может быть - ровно то, что игрок увидит,
 * нажав. Рисовать отдельную обложку значит обещать не то, что внутри.
 */
await sharp(SRC)
  .extract({ left: 8, top: 0, width: 1090, height: 647 })
  .resize(640, 380, { fit: 'cover' })
  .webp({ quality: 84 })
  .toFile(OUT + 'slot-cover-treasure.webp');
made.push('slot-cover-treasure');

